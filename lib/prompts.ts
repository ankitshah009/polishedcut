import { TITLE_SECONDS } from "./config";
import type { Caption, EDL, Overlay, SourceClip } from "./schema";

export const EDL_RULES = `EDL schema (JSON):
{"title": string (optional; if non-empty a ${TITLE_SECONDS}s title card is shown BEFORE the first cut),
 "cuts": [{"id": "c1", "clipId": string, "srcIn": number, "srcOut": number, "reason": string}, ...],
 "captions": [{"text": string, "start": number, "end": number}, ...],
 "overlays": [{"text": string, "start": number, "end": number, "position": "lower-third" | "top" | "center"}, ...] (optional),
 "endTitle": string (optional; if non-empty a ${TITLE_SECONDS}s closing card is shown AFTER the last cut),
 "audio": {"denoise": boolean, "musicGainDb": number} (optional),
 "music": {"prompt": string} | null}
Rules:
- Cuts play back-to-back in list order. srcIn/srcOut are seconds in the SOURCE clip, 0 <= srcIn < srcOut <= clip duration.
- Cut ids are c1..cN in order.
- Caption start/end are on the OUTPUT timeline: output time = (title ? ${TITLE_SECONDS}s : 0) + sum of previous cut durations + (source time - srcIn).
  Captions must match the words actually spoken at that output time. Captions are ONLY for transcribing speech.
- Overlays are on-screen labels NOT tied to speech: chapter titles, lower-thirds (who/what/where), "what's happening" text
  explaining what the viewer is looking at, feature names, numbers. Same OUTPUT-timeline times as captions. Use them when the
  brief asks for on-screen text, labels, explanations or a walkthrough; keep each to one short line, 2-5s. Default position
  "lower-third"; "top" when captions run at the same time; "center" for a chapter title over a quiet shot.
- endTitle is a closing line shown on a full-frame card after the last cut (a sign-off, a tagline, "built with ..."). Use it when
  the brief asks for a closing card or an ending line, otherwise omit it.
- audio.denoise: true when the footage is noisy (hiss, hum, wind, room noise). audio.musicGainDb sets the music level in dB:
  -10 is clearly present, -15 the default, -20 very quiet under speech. Omit audio when nothing is asked.
- Never cut in the middle of a word or sentence: place srcIn/srcOut in pauses between words using the transcripts.
- Hit the target duration from the brief (total = title card + sum of cut durations + closing card); if none given, keep it tight (about 30s).
- Avoid jarring jump cuts (for example two very similar shots from the same clip separated by a tiny gap).
- music.prompt is ONE line describing an instrumental music bed that matches the mood of the brief (genre, tempo, instruments, feel);
  it is generated by a music model and mixed quietly under the dialogue. Use null if the brief says no music or the footage is music already.`;

export function describeClips(clips: { clip: SourceClip }[]): string {
  return clips
    .map(({ clip }) => {
      const words =
        clip.transcript.map((w) => `[${w.start.toFixed(2)}-${w.end.toFixed(2)}]${w.text}`).join(" ") ||
        "(no speech / no transcript)";
      return `clipId=${clip.id} duration=${clip.duration.toFixed(2)}s\ntranscript: ${words}`;
    })
    .join("\n\n");
}

export const GENERATED_RULES = `Generated shots (optional, "generated" array in the EDL):
- ONLY when the footage lacks something the brief needs (an opening or closing sting, an establishing shot,
  an abstract transition), you may request up to two shots that a video model generates:
  "generated": [{"id": "g1", "prompt": string, "seconds": number}, ...] with ids g1 and g2, 2 <= seconds <= 8.
- The prompt describes one continuous shot: subject, setting, camera move, lighting, mood. No text, no people talking.
- Reference a generated shot in cuts with clipId "g1"/"g2" and 0 <= srcIn < srcOut <= its seconds.
- Prefer the real footage. Omit "generated" (or use []) when the clips already cover the brief.`;

export function draftPrompt(brief: string, clips: { clip: SourceClip }[]): string {
  return (
    "You are a professional video editor. Watch every clip above and build an edit decision list " +
    `that fulfils this brief.\n\nBRIEF:\n${brief}\n\nCLIPS:\n${describeClips(clips)}\n\n${EDL_RULES}\n\n${GENERATED_RULES}\n\n` +
    "Return ONLY the EDL JSON."
  );
}

export function timelineText(edl: EDL): string {
  let t = edl.title ? TITLE_SECONDS : 0;
  const lines: string[] = edl.title ? [`title card '${edl.title}': 0.00-${t.toFixed(2)}`] : [];
  for (const c of edl.cuts) {
    const d = c.srcOut - c.srcIn;
    lines.push(
      `${c.id}: output ${t.toFixed(2)}-${(t + d).toFixed(2)} <- ${c.clipId} ` +
        `[${c.srcIn.toFixed(2)}-${c.srcOut.toFixed(2)}] (${c.reason})`,
    );
    t += d;
  }
  if (edl.endTitle) {
    lines.push(`closing card '${edl.endTitle}': ${t.toFixed(2)}-${(t + TITLE_SECONDS).toFixed(2)}`);
    t += TITLE_SECONDS;
  }
  lines.push(`total duration: ${t.toFixed(2)}s`);
  lines.push(edl.music?.prompt ? `music bed: ${JSON.stringify(edl.music.prompt)}` : "music bed: none");
  if (edl.audio?.denoise || edl.audio?.musicGainDb != null) {
    const bits = [edl.audio.denoise ? "denoise on" : "", edl.audio.musicGainDb != null ? `music ${edl.audio.musicGainDb}dB` : ""].filter(Boolean);
    lines.push(`audio: ${bits.join(", ")}`);
  }
  edl.captions.forEach((cap: Caption, i: number) => {
    lines.push(`caption[${i}] ${cap.start.toFixed(2)}-${cap.end.toFixed(2)}: ${JSON.stringify(cap.text)}`);
  });
  (edl.overlays ?? []).forEach((ov: Overlay, i: number) => {
    lines.push(`overlay[${i}] ${ov.start.toFixed(2)}-${ov.end.toFixed(2)} (${ov.position}): ${JSON.stringify(ov.text)}`);
  });
  return lines.join("\n");
}

export function critiquePrompt(brief: string, edl: EDL, clips: { clip: SourceClip }[]): string {
  return (
    "You are a demanding senior editor reviewing the rendered edit above against the brief.\n\n" +
    `BRIEF:\n${brief}\n\nSOURCE CLIPS:\n${describeClips(clips)}\n\n` +
    `CURRENT EDL (JSON):\n${JSON.stringify(edl)}\n\nCOMPUTED OUTPUT TIMELINE:\n${timelineText(edl)}\n\n${EDL_RULES}\n\n` +
    "Watch the rendered video and produce checks (each with name, passed, at = output-timeline seconds, note):\n" +
    "- one check per requirement in the brief (name it 'brief: ...')\n" +
    "- captions in sync with speech and text matches what is said\n" +
    "- no mid-sentence or mid-word cuts\n" +
    "- no jarring jump cuts\n" +
    "- duration matches target\n" +
    "- title card readable (if a title is set); closing card readable (if endTitle is set)\n" +
    "- overlays legible, on screen long enough, and showing what the brief asked to label\n\n" +
    "For every failure, add patches that fix it. PatchOp fields: op in " +
    "[trim, remove_cut, insert_cut, move_cut, set_caption, remove_caption, add_caption, set_title, set_music, " +
    "add_overlay, set_overlay, remove_overlay, set_end_title, set_audio], " +
    "cutId (existing ids like c1), index (caption/overlay index or insert/move position), srcIn, srcOut, clipId, " +
    "text, start, end, position, denoise, gainDb. Source times are source-clip seconds; caption and overlay times are output-timeline seconds.\n" +
    "set_music: text is a new one-line instrumental music prompt (use when the bed clashes with the mood or the brief), " +
    'or "" to remove the music bed. Only use set_music when the music itself fails a check.\n' +
    "Director's notes and brief items that the cut list cannot express map to these ops:\n" +
    "- on-screen text, labels, lower-thirds, 'text showing what is going on', chapter titles -> add_overlay (text, start, end, " +
    "position in [lower-third, top, center]) / set_overlay (index) / remove_overlay (index). NEVER put such text in captions; " +
    "captions are only for spoken words.\n" +
    '- a closing line or end card ("this is being built with...", a sign-off, a tagline) -> set_end_title (text; "" removes it).\n' +
    "- noisy audio (hiss, hum, wind, room noise) -> set_audio with denoise: true.\n" +
    "- music too quiet / 'more music' -> set_audio with gainDb between -10 (present) and -20 (very quiet); too loud -> lower it.\n" +
    "Caption rules for patches: caption text must be the exact words from the transcript and nothing else " +
    "(no notes, no alternatives, no commentary). If a caption is early or late, fix its timing with " +
    "set_caption start/end; do not rewrite its text. Keep summary to one sentence.\n" +
    "Return empty patches ONLY if every check passes.\n" +
    'Return ONLY JSON: {"checks": [...], "patches": [...], "summary": string}'
  );
}
