// Shared contract. Every server module and the UI read and write these shapes only.
// Paths inside a run (clip paths, iteration videos) are relative to the run directory,
// so runs can be moved or served without rewriting run.json.
import { z } from "zod";

export const WordSchema = z.object({
  text: z.string(),
  start: z.number(), // seconds, in the source clip
  end: z.number(),
});
export type Word = z.infer<typeof WordSchema>;

export const SourceClipSchema = z.object({
  id: z.string(), // "clip1", "clip2", ...
  path: z.string(), // e.g. "src/clip1_a.mp4"
  duration: z.number(), // seconds, from ffprobe
  transcript: z.array(WordSchema).default([]),
});
export type SourceClip = z.infer<typeof SourceClipSchema>;

export const CutSchema = z.object({
  id: z.string(), // "c1", "c2", ... renumbered after every draft and patch
  clipId: z.string(),
  srcIn: z.number(), // seconds in the source clip
  srcOut: z.number(),
  reason: z.string().default(""),
});
export type Cut = z.infer<typeof CutSchema>;

export const CaptionSchema = z.object({
  text: z.string(),
  start: z.number(), // seconds on the OUTPUT timeline
  end: z.number(),
});
export type Caption = z.infer<typeof CaptionSchema>;

// On-screen label NOT tied to speech: chapter titles, "what's happening" text, lower-thirds.
// Lives in edl.overlays, never in captions, so the caption-vs-speech lint ignores it.
export const OverlayPositionSchema = z.enum(["top", "lower-third", "center"]);
export type OverlayPosition = z.infer<typeof OverlayPositionSchema>;
export const OverlaySchema = z.object({
  text: z.string(),
  start: z.number(), // seconds on the OUTPUT timeline
  end: z.number(),
  position: OverlayPositionSchema.default("lower-third"),
});
export type Overlay = z.infer<typeof OverlaySchema>;

// Program-audio treatment and music level, both optional.
export const AudioSettingsSchema = z.object({
  denoise: z.boolean().default(false), // afftdn + highpass on the dialogue before mixing
  musicGainDb: z.number().optional(), // wins over music.gainDb and the MUSIC_GAIN_DB default
});
export type AudioSettings = z.infer<typeof AudioSettingsSchema>;

// What Argon is asked to return. Output size and frame rate are fixed by the app.
export const EdlDraftSchema = z.object({
  title: z.string().default(""), // non-empty -> a title card is shown before the first cut
  cuts: z.array(CutSchema),
  captions: z.array(CaptionSchema).default([]),
  overlays: z.array(OverlaySchema).default([]),
  endTitle: z.string().trim().optional(), // non-empty -> a closing card (TITLE_SECONDS) is appended after the last cut
  audio: AudioSettingsSchema.optional(),
  // Instrumental music bed generated by Lyria. `file` is relative to the run directory.
  music: z.object({ prompt: z.string(), gainDb: z.number().optional(), file: z.string().optional() }).nullish(),
  // Up to two shots Omni generates for the cut (ids g1/g2); cuts may reference them like footage.
  generated: z
    .array(z.object({ id: z.string(), prompt: z.string(), seconds: z.number().min(2).max(8) }))
    .max(2)
    .optional(),
});

export const EdlSchema = EdlDraftSchema.extend({
  width: z.number().int(),
  height: z.number().int(),
  fps: z.number().int(),
  titleImage: z.string().optional(), // Nano Banana title card background, relative to the run directory
  endImage: z.string().optional(), // Nano Banana closing card background, relative to the run directory
});
export type EDL = z.infer<typeof EdlSchema>;

export const CheckSchema = z.object({
  name: z.string(), // e.g. "brief: shows the keynote"
  passed: z.boolean(),
  at: z.number().nullish(), // output-timeline seconds, when the failure can be localized
  note: z.string().default(""),
});
export type Check = z.infer<typeof CheckSchema>;

export const PatchOpSchema = z.object({
  op: z.enum([
    "trim",
    "remove_cut",
    "insert_cut",
    "move_cut",
    "set_caption",
    "remove_caption",
    "add_caption",
    "set_title",
    "set_music", // text = new music prompt, or "" to remove the music bed
    // The five below are applied by applyExtraPatch in lib/extras.ts.
    "add_overlay", // text, start, end, position?
    "set_overlay", // index (overlay index), text?, start?, end?, position?
    "remove_overlay", // index
    "set_end_title", // text = closing-card line, or "" to remove the end card
    "set_audio", // denoise?, gainDb? (music level in dB, -10..-20 is audible but under speech)
  ]),
  cutId: z.string().nullish(),
  index: z.number().int().nullish(), // caption/overlay index, or insert/move position
  srcIn: z.number().nullish(),
  srcOut: z.number().nullish(),
  clipId: z.string().nullish(),
  text: z.string().nullish(),
  start: z.number().nullish(),
  end: z.number().nullish(),
  position: OverlayPositionSchema.nullish(), // add_overlay / set_overlay
  denoise: z.boolean().nullish(), // set_audio
  gainDb: z.number().nullish(), // set_audio: music level
});
export type PatchOp = z.infer<typeof PatchOpSchema>;

export const CritiqueSchema = z.object({
  checks: z.array(CheckSchema),
  patches: z.array(PatchOpSchema).default([]),
  summary: z.string().default(""),
});
export type Critique = z.infer<typeof CritiqueSchema>;

export function allPassed(critique: Critique): boolean {
  return critique.checks.every((c) => c.passed);
}

export const IterationSchema = z.object({
  n: z.number().int(), // 1-based
  edl: EdlSchema,
  video: z.string(), // rendered mp4, relative to the run directory, e.g. "iter1.mp4"
  critique: CritiqueSchema.nullish(),
  note: z.string().optional(), // director's note that produced this iteration (revisions only)
});
export type Iteration = z.infer<typeof IterationSchema>;

export const RunStatusSchema = z.enum(["queued", "drafting", "rendering", "critiquing", "done", "error"]);
export type RunStatus = z.infer<typeof RunStatusSchema>;

export const RunSchema = z.object({
  id: z.string(),
  brief: z.string(),
  createdAt: z.string(), // ISO 8601
  clips: z.array(SourceClipSchema),
  iterations: z.array(IterationSchema).default([]),
  status: RunStatusSchema.default("queued"),
  error: z.string().default(""),
  warnings: z.array(z.string()).default([]),
  // Where the footage arrived from: "web" (dashboard upload), "demo", or a chat platform via Photon
  // Spectrum ("imessage", "whatsapp-business", "telegram", "slack"). Older run.json files have neither.
  source: z.string().optional(),
  // The requester as the platform identifies them (phone number, chat id); set by the chat adapter.
  requester: z.string().optional(),
  timings: z.array(z.object({ stage: z.string(), ms: z.number() })).default([]).optional(), // wall-clock per stage
  // One entry per model call / file upload, for cost estimates (see lib/pricing.ts).
  usage: z
    .array(
      z.object({
        model: z.string(),
        inputTokens: z.number(),
        outputTokens: z.number(),
        cachedTokens: z.number().default(0),
        ms: z.number(),
      }),
    )
    .default([])
    .optional(),
});
export type Run = z.infer<typeof RunSchema>;
export type RunUsage = NonNullable<Run["usage"]>[number];
